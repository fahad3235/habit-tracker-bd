const BN_DIGITS = '০১২৩৪৫৬৭৮৯';
function htLocalizeDigits(s, lang) {
  s = String(s);
  if (lang !== 'bn') return s;
  return s.replace(/[0-9]/g, d => BN_DIGITS[+d]);
}
